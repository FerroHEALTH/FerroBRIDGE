//! The HL7 Europe element of each draft `EEHRxF` annex element the category
//! crosswalks do not reach.
//!
//! Each row names an annex element (annex, Xt-EHR model, draft element) and
//! the element id of the category's HL7 Europe profile that carries it, or
//! `None` where neither the profile nor the R4 resource has a place for it.
//! No specification publishes this map: our own design, held to the pinned
//! profile snapshots by [`super::every_path_is_an_element_of_its_profile`].

use eehrxf::draft::Annex;

/// One annex element and the profile element that carries it.
pub(super) struct Path {
    /// The annex of the element.
    pub(super) annex: Annex,
    /// The Xt-EHR model the draft crosswalk sets the element in.
    pub(super) model: &'static str,
    /// The draft element.
    pub(super) element: &'static str,
    /// The profile element id, or `None` where nothing carries it.
    pub(super) eps: Option<&'static str>,
}

/// The row of `element` of `model` in `annex`, carried by `eps`.
const fn path(
    annex: Annex,
    model: &'static str,
    element: &'static str,
    eps: Option<&'static str>,
) -> Path {
    Path {
        annex,
        model,
        element,
        eps,
    }
}

