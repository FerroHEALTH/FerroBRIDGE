//! The decision on each element of draft `EEHRxF` Annex III Table 2 and
//! Annex X that differs from the Xt-EHR models 1.0.0 and that no category
//! crosswalk reaches.
//!
//! Annex III Table 2 (data group metadata) applies to every data group and
//! Annex X (the common data groups of Art 7) to every category that uses a
//! group, so neither belongs to one category's crosswalk. Each row names the
//! element of an HL7 Europe base 2.0.1 profile or an R4 core definition that
//! carries the annex element, or `None` where no element common to the data
//! groups carries it, and says why from the annex text, keeping the draft's
//! name and cardinality where the two texts differ. No specification
//! publishes this map: our own design, held to the definitions by
//! [`super::every_common_decision_names_an_element_of_its_definition`].

use eehrxf::draft::Annex;

/// One decision: the annex element and where it goes.
pub(super) struct Decision {
    /// The annex of the element.
    pub(super) annex: Annex,
    /// The draft model the element belongs to.
    pub(super) model: &'static str,
    /// The draft element.
    pub(super) element: &'static str,
    /// The canonical URL of the definition `carried` is an element of.
    pub(super) definition: &'static str,
    /// The element id that carries the annex element, or `None` where no
    /// element common to the data groups carries it.
    pub(super) carried: Option<&'static str>,
    /// Why, from the annex text.
    pub(super) why: &'static str,
}

/// The decision on `element` of `model` in `annex`.
const fn decision(
    annex: Annex,
    model: &'static str,
    element: &'static str,
    definition: &'static str,
    carried: Option<&'static str>,
    why: &'static str,
) -> Decision {
    Decision {
        annex,
        model,
        element,
        definition,
        carried,
        why,
    }
}

